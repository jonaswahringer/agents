(async () => {
  'use strict';
  const root = document.getElementById('c4-explorer');
  const checks = [];
  const assert = (value, message) => { if (!value) throw new Error(message); checks.push(message); };
  const settle = () => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)));
  const click = async selector => { const target = root.querySelector(selector); if (!target) throw new Error('Missing target: ' + selector); target.focus(); target.click(); await settle(); };
  const state = () => window.c4Demo.inspect();
  const assertBoundary = () => {
    const boundary = root.querySelector('.c4-boundary').getBoundingClientRect();
    const internal = [...root.querySelectorAll('.c4-node:not(.is-external)')].map(node => node.getBoundingClientRect());
    const external = [...root.querySelectorAll('.c4-node.is-external')].map(node => node.getBoundingClientRect());
    assert(internal.every(box => box.top >= boundary.top && box.bottom <= boundary.bottom), 'Internal elements are visually inside their C4 boundary');
    assert(external.every(box => box.top >= boundary.bottom), 'External dependencies are visually outside the C4 boundary');
    assert([...root.querySelectorAll('.c4-node')].every(node => node.scrollHeight <= node.clientHeight && node.scrollWidth <= node.clientWidth), 'Typed element labels fit their shapes');
  };
  await c4Demo.navigate('context', { trail: C4DemoSource.rootTrail('demo') });
  await settle();
  assert(root.querySelector('[data-action="back"]').hidden, 'Root scope hides the parent navigation control');
  assert(root.querySelector('.c4-node.c4-node--person circle') && root.querySelector('.c4-node.c4-node--system'), 'Context uses an actor silhouette and software system blocks');
  assert(!root.querySelector('.c4-boundary'), 'Context does not invent a containment boundary around unrelated systems');
  await click('[data-node-id="commerce"]');
  assert(state().viewId === 'containers', 'Context drills into containers');
  const back = root.querySelector('[data-action="back"]');
  assert(!back.hidden && back.closest('.c4-scope'), 'Parent navigation is visible inside the diagram');
  assert(back.textContent.includes('Back to parent') && back.textContent.includes('Commerce'), 'Back button names its destination');
  assert(document.activeElement === root.querySelector('h2'), 'New scope receives focus');
  assert(matchMedia('(prefers-reduced-motion: reduce)').matches ? document.getAnimations().length === 0 : document.getAnimations().length > 0, 'Drill-down follows the motion preference');
  assert(root.querySelector('.c4-node.c4-node--application') && root.querySelector('.c4-node.c4-node--database') && root.querySelector('.c4-node.c4-node--queue'), 'Container view distinguishes applications, data stores, and message brokers');
  assert(root.querySelector('.c4-boundary-label').textContent.includes('Software system boundary'), 'Container view identifies its software system boundary');
  assertBoundary();
  await click('[data-node-id="api"]');
  assert(state().viewId === 'components', 'Container drills into components');
  assert(root.querySelectorAll('.c4-node.c4-node--component').length === 4, 'Component view uses four module shapes');
  assert(root.querySelector('.c4-boundary-label').textContent.includes('Container boundary'), 'Component view identifies its container boundary');
  assert(root.querySelector('[data-node-id="db"]').classList.contains('c4-node--database'), 'A database stays a cylinder when referenced from a component view');
  assert(root.querySelector('[data-node-id="checkout"] .c4-kind').textContent.includes('TypeScript'), 'Components expose their implementation technology');
  assertBoundary();
  await click('[data-action="back"]');
  assert(state().viewId === 'containers' && document.activeElement.dataset.nodeId === 'api', 'Up restores parent block focus');
  const flow = root.querySelector('select'); flow.value = 'checkout'; flow.dispatchEvent(new Event('change', { bubbles: true }));
  assert(root.querySelectorAll('.c4-edge.is-active').length === 6, 'Flow highlights all six runtime relationships');
  assert(root.querySelector('.c4-relations li').textContent.includes('Storefront → Order API'), 'Accessible flow list preserves step order');
  await click('[data-edge-id="publish"]');
  assert(root.querySelector('.c4-detail').textContent.includes('asynchronous'), 'Relationship details expose protocol and delivery type');
  root.dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape', bubbles: true })); await settle();
  assert(state().viewId === 'context', 'Escape returns to parent scope');
  await click('[data-action="sample"]');
  assert(state().viewId === 'scale', 'Scale fixture opens');
  assert(root.querySelectorAll('.c4-node').length <= 12, '10,400-element model keeps mounted nodes within budget');
  assert(root.querySelectorAll('.c4-relations li button').length <= 36, 'Relationship controls stay bounded');
  assert(root.querySelector('.c4-relations summary').textContent.includes('outside this page'), 'Off-page relationships are disclosed');
  const parentPage = state().page + 1;
  await click('[data-action="next"]');
  assert(state().page === parentPage, 'Paging reaches unmounted elements');
  const search = root.querySelector('input'); search.value = 'System 400 / Service 25'; search.dispatchEvent(new Event('input', { bubbles: true })); await settle();
  assert(root.querySelectorAll('[data-result]').length === 1, 'Search locates a deep element across scopes');
  await click('[data-result="0"]');
  assert(state().viewId === 'scale-399' && state().selected === 's399-24', 'Search opens the target scope and selects its element');
  assert(root.querySelector('[data-node-id="s399-24"]') !== null, 'Search opens the page containing the target');
  assert(document.activeElement.dataset.nodeId === 's399-24', 'Search result receives keyboard focus');
  await click('[data-action="back"]');
  assert(state().page === parentPage, 'Returning preserves the parent page');
  await click('[data-action="sample"]');
  const original = C4DemoSource.getView;
  let release;
  C4DemoSource.getView = (id, options) => id === 'components' ? new Promise(resolve => { release = () => resolve(original(id, options && { ...options, signal: undefined })); }) : original(id, options);
  try {
    const slow = c4Demo.navigate('components');
    await c4Demo.navigate('containers', { trail: [{ id: 'context', name: 'Commerce' }, { id: 'containers', name: 'Commerce platform', via: 'commerce' }] });
    release(); await slow;
    assert(state().viewId === 'containers', 'A stale provider response cannot replace the latest scope');
  } finally { C4DemoSource.getView = original; }
  await c4Demo.navigate('context', { trail: C4DemoSource.rootTrail('demo') });
  await new Promise(resolve => setTimeout(resolve, 450));
  assert(root.querySelectorAll('.c4-transition').length === 0, 'Completed transitions leave no overlay nodes');
  const clipped = [...root.querySelectorAll('.c4-node')].filter(node => node.scrollWidth > node.clientWidth || node.scrollHeight > node.clientHeight);
  assert(clipped.length === 0, 'Visible node text fits the cards');
  assert(document.documentElement.scrollWidth <= innerWidth, 'The explorer creates no horizontal document overflow');
  c4Demo.destroy();
  await c4Demo.navigate('containers');
  assert(c4Demo.inspect().viewId === 'context' && !root.hasAttribute('aria-busy'), 'Navigation after destroy leaves the page unchanged');
  globalThis.c4Demo = C4Explorer.mount(root, C4DemoSource); await settle();
  assert(c4Demo.inspect().viewId === 'context', 'A destroyed explorer can be replaced without duplicate listeners');
  return { passed: checks.length, checks, viewport: { width: innerWidth, height: innerHeight }, reducedMotion: matchMedia('(prefers-reduced-motion: reduce)').matches };
})()
